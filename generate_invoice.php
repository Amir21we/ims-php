<?php
require 'config.php';
requireRole([ROLE_ADMIN, ROLE_MANAGER, ROLE_CUSTOMER]);
require 'libs/fpdf.php';

$type = $_GET['type'] ?? 'sales';
$id = (int)($_GET['id'] ?? 0);
$cid = companyId();
$role = currentRole();

if ($id <= 0) die('Invalid Order ID');

// For customers, verify they own this sales order
if ($role === ROLE_CUSTOMER) {
    if ($type !== 'sales') die('Access Denied');
    
    $check = $pdo->prepare("
        SELECT so.SalesOrderID 
        FROM tblsalesorders so
        JOIN tblcustomers c ON c.CustomerID = so.CustomerID
        JOIN tblusers u ON u.UserName = c.Email
        WHERE so.SalesOrderID = ? AND u.UserID = ? AND so.CompanyID = ?
    ");
    $check->execute([$id, $_SESSION['user_id'], $cid]);
    if (!$check->fetch()) die('Access Denied: You do not own this order.');
}

if ($type === 'sales') {
    $stmt = $pdo->prepare("
        SELECT o.*, c.CustomerName, c.Email, c.Phone, c.Address 
        FROM tblsalesorders o 
        LEFT JOIN tblcustomers c ON c.CustomerID = o.CustomerID 
        WHERE o.SalesOrderID = ? AND o.CompanyID = ?
    ");
    $stmt->execute([$id, $cid]);
    $order = $stmt->fetch();
    
    if (!$order) die('Order not found');

    $itemsStmt = $pdo->prepare("
        SELECT i.*, p.ProductName, p.Unit 
        FROM tblsalesorderitems i 
        JOIN tblproducts p ON p.ProductID = i.ProductID 
        WHERE i.SalesOrderID = ?
    ");
    $itemsStmt->execute([$id]);
    $items = $itemsStmt->fetchAll();

    $docTitle = 'SALES INVOICE';
    $orderNum = 'INV-' . str_pad($id, 6, '0', STR_PAD_LEFT);
    $partnerLabel = 'Bill To:';
    $partnerName = $order['CustomerName'] ?: 'Walk-in Customer';

} else {
    // purchase
    $stmt = $pdo->prepare("
        SELECT o.*, s.SupplierName, s.Email, s.Phone, s.Address 
        FROM tblpurchaseorders o 
        LEFT JOIN tblsuppliers s ON s.SupplierID = o.SupplierID 
        WHERE o.PurchaseOrderID = ? AND o.CompanyID = ?
    ");
    $stmt->execute([$id, $cid]);
    $order = $stmt->fetch();

    if (!$order) die('Order not found');

    $itemsStmt = $pdo->prepare("
        SELECT i.*, p.ProductName, p.Unit 
        FROM tblpurchaseorderitems i 
        JOIN tblproducts p ON p.ProductID = i.ProductID 
        WHERE i.PurchaseOrderID = ?
    ");
    $itemsStmt->execute([$id]);
    $items = $itemsStmt->fetchAll();

    $docTitle = 'PURCHASE ORDER';
    $orderNum = 'PO-' . str_pad($id, 6, '0', STR_PAD_LEFT);
    $partnerLabel = 'Supplier:';
    $partnerName = $order['SupplierName'] ?: 'Walk-in Supplier';
}

// Generate PDF
class PDF extends FPDF {
    public $titleText = '';
    function Header() {
        $this->SetFont('Arial','B',20);
        $this->SetTextColor(0, 212, 170); // Teal
        $this->Cell(100, 10, 'StockMaster', 0, 0, 'L');
        
        $this->SetFont('Arial','B',16);
        $this->SetTextColor(40,40,40);
        $this->Cell(90, 10, $this->titleText, 0, 1, 'R');
        $this->Ln(5);
    }
    
    function Footer() {
        $this->SetY(-15);
        $this->SetFont('Arial','I',8);
        $this->SetTextColor(128);
        $this->Cell(0,10,'Page '.$this->PageNo().' / {nb} - Generated by StockMaster',0,0,'C');
    }
}

$pdf = new PDF();
$pdf->titleText = $docTitle;
$pdf->AliasNbPages();
$pdf->AddPage();

// Company Info
$pdf->SetFont('Arial','B',12);
$pdf->SetTextColor(40,40,40);
$pdf->Cell(100, 6, 'Company ' . $cid, 0, 0, 'L');

$pdf->SetFont('Arial','',10);
$pdf->SetTextColor(100,100,100);
$pdf->Cell(90, 6, 'Order #: ' . $orderNum, 0, 1, 'R');

$pdf->Cell(100, 6, '123 Business Avenue', 0, 0, 'L');
$pdf->Cell(90, 6, 'Date: ' . date('M d, Y', strtotime($order['OrderDate'])), 0, 1, 'R');

$pdf->Cell(100, 6, 'City, State 12345', 0, 0, 'L');
$pdf->Cell(90, 6, 'Status: ' . $order['Status'], 0, 1, 'R');

$pdf->Ln(10);

// Partner Info
$pdf->SetFont('Arial','B',11);
$pdf->SetTextColor(40,40,40);
$pdf->Cell(100, 6, $partnerLabel, 0, 1, 'L');

$pdf->SetFont('Arial','',10);
$pdf->Cell(100, 6, $partnerName, 0, 1, 'L');
$pdf->SetTextColor(100,100,100);
if ($order['Address'] ?? '') $pdf->Cell(100, 5, $order['Address'], 0, 1, 'L');
if ($order['Phone'] ?? '') $pdf->Cell(100, 5, 'Phone: ' . $order['Phone'], 0, 1, 'L');
if ($order['Email'] ?? '') $pdf->Cell(100, 5, 'Email: ' . $order['Email'], 0, 1, 'L');

$pdf->Ln(15);

// Table Header
$pdf->SetFont('Arial','B',10);
$pdf->SetTextColor(255,255,255);
$pdf->SetFillColor(13, 27, 42); // Navy
$pdf->Cell(90, 8, ' Item Description', 1, 0, 'L', true);
$pdf->Cell(30, 8, ' Quantity', 1, 0, 'C', true);
$pdf->Cell(35, 8, ' Unit Price', 1, 0, 'R', true);
$pdf->Cell(35, 8, ' Line Total', 1, 1, 'R', true);

// Table Body
$pdf->SetFont('Arial','',10);
$pdf->SetTextColor(40,40,40);
$fill = false;

foreach ($items as $item) {
    $pdf->SetFillColor(245, 247, 250);
    $pdf->Cell(90, 8, ' ' . $item['ProductName'], 1, 0, 'L', $fill);
    $pdf->Cell(30, 8, $item['Quantity'] . ' ' . ($item['Unit'] ?: 'pcs'), 1, 0, 'C', $fill);
    $pdf->Cell(35, 8, '$' . number_format($item['UnitPrice'], 2), 1, 0, 'R', $fill);
    $pdf->Cell(35, 8, '$' . number_format($item['LineTotal'], 2), 1, 1, 'R', $fill);
    $fill = !$fill;
}

// Total
$pdf->SetFont('Arial','B',11);
$pdf->Cell(120, 8, '', 0, 0);
$pdf->Cell(35, 8, 'Total Amount:', 1, 0, 'R');
$pdf->SetTextColor(0, 184, 148); // Teal Dark
$pdf->Cell(35, 8, '$' . number_format($order['TotalAmount'], 2), 1, 1, 'R');

if (!empty($order['Notes'])) {
    $pdf->Ln(10);
    $pdf->SetFont('Arial','B',10);
    $pdf->SetTextColor(40,40,40);
    $pdf->Cell(0, 6, 'Notes / Instructions:', 0, 1, 'L');
    $pdf->SetFont('Arial','',9);
    $pdf->SetTextColor(100,100,100);
    $pdf->MultiCell(0, 5, $order['Notes']);
}

$pdf->Output('I', $orderNum . '.pdf');
?>
